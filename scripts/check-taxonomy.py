def run_all_checks(taxo: dict, root: Path = ROOT) -> int:
    """Every drift-class checker, summed. The single dispatch point both `main()` and
    `selftest()` call, so a new checker is wired into both by adding one line here."""
    return (
        check(taxo, root=root)
        + check_reference_formats(taxo, root=root)
        + check_feature_registry(taxo, root=root)
        + check_schema_renames(taxo, root=root)
        + check_unreadable_files(taxo, root=root)
    )


def _assert_harness_discriminates(taxo: dict) -> tuple[int, int]:
    """The `fixture-that-must-discriminate` self-check (T-02-10, methodology rule 5e).

    A harness can exit 0 having done nothing — the risk here is a calibration matrix
    that always reports "pass" (or always "fail") regardless of what a fixture's seeded
    text actually does, making every entry in FIXTURES decorative. This proves the
    want-vs-got comparison that drives the loop above is not vacuous: it takes two
    ALREADY-PROVEN fixtures (one whose real content genuinely fails a check, one whose
    real content genuinely passes), constructs a copy of each with its `expect` field
    deliberately flipped to the WRONG value, and asserts the resulting disagreement
    (`got != expect`) is real — i.e. that `got` tracks the fixture's actual seeded
    content, not merely echoes back whatever `expect` says. A harness that could not
    tell these apart would be exactly the "exited 0, caught nothing" failure mode.

    Returns (checks_run, problems) — folded into --selftest's own N/M totals.
    """
    true_fail = next(fx for fx in FIXTURES if fx["id"] == "denied-term-prose")
    true_pass = next(fx for fx in FIXTURES if fx["id"] == "exempt-path-skipped")
    mislabelled = [
        {**true_fail, "id": "fixture-that-must-discriminate-fail-mislabelled-pass", "expect": "pass"},
        {**true_pass, "id": "fixture-that-must-discriminate-pass-mislabelled-fail", "expect": "fail"},
    ]
    problems = 0
    for fx in mislabelled:
        tmp_root = Path(tempfile.mkdtemp(prefix="check-taxonomy-selftest-"))
        try:
            target = tmp_root / fx["path"]
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(fx["text"], encoding="utf-8")
            fx_taxo = fx["taxo_patch"](taxo) if "taxo_patch" in fx else taxo
            got_problems = run_all_checks(fx_taxo, root=tmp_root)
            got = "fail" if got_problems else "pass"
            if got == fx["expect"]:
                # The deliberate mislabel should make got/expect disagree. If they
                # instead agree, either coincidence or (more likely) a vacuous
                # comparison — either way this self-check must name it and fail.
                print(
                    f"ERROR: fixture '{fx['id']}' was mislabelled on purpose "
                    f"(expect={fx['expect']!r}) and the harness did NOT catch the "
                    f"disagreement between seeded content and label — the "
                    f"discrimination check itself is vacuous (methodology 5e, "
                    f"T-02-10)",
                    file=sys.stderr,
                )
                problems += 1
        finally:
            shutil.rmtree(tmp_root, ignore_errors=True)
    return len(mislabelled), problems


def selftest(taxo: dict) -> tuple[int, int]:
    """Run FIXTURES against fresh temp trees, then the discrimination self-check;
    return (fixtures_run, problems)."""
    total_problems = 0
    for fx in FIXTURES:
        tmp_root = Path(tempfile.mkdtemp(prefix="check-taxonomy-selftest-"))
        try:
            target = tmp_root / fx["path"]
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(fx["text"], encoding="utf-8")
            fx_taxo = fx["taxo_patch"](taxo) if "taxo_patch" in fx else taxo
            problems = run_all_checks(fx_taxo, root=tmp_root)
            got = "fail" if problems else "pass"
            if got != fx["expect"]:
                print(
                    f"ERROR: fixture '{fx['id']}' expected {fx['expect']} but got "
                    f"{got} — {fx['why']}",
                    file=sys.stderr,
                )
                total_problems += 1
        finally:
            shutil.rmtree(tmp_root, ignore_errors=True)
    extra_count, extra_problems = _assert_harness_discriminates(taxo)
    total_problems += extra_problems
    return len(FIXTURES) + extra_count, total_problems


def main() -> int:
    taxo = load_taxonomy()
    assert_carveouts_implemented(taxo)
    args = sys.argv[1:]
    valid = {"--check", "--selftest"}
    if len(args) > 1 or (args and args[0] not in valid):
        print("usage: check-taxonomy.py [--check|--selftest]", file=sys.stderr)
        return 2

    if args and args[0] == "--selftest":
        count, problems = selftest(taxo)
        print(f"{count} fixtures run, {problems} problem(s)")
        return 1 if problems else 0

    problems = run_all_checks(taxo)
    files_checked = sum(1 for _ in walk(taxo))
    print(f"{files_checked} files checked, {problems} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
